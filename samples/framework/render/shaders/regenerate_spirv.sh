#!/usr/bin/env bash
# Rebuilds flat_color_spirv.h and text_sdf_spirv.h from the GLSL sources next to this script.
# Needs glslangValidator and python3.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

generate() {
    local name="$1"
    glslangValidator -V "$here/${name}.vert.glsl" -S vert -o "$tmp/${name}.vert.spv"
    glslangValidator -V "$here/${name}.frag.glsl" -S frag -o "$tmp/${name}.frag.spv"
    python3 - "$name" "$tmp/${name}.vert.spv" "$tmp/${name}.frag.spv" "$here/../${name}_spirv.h" <<'PY'
import sys
name = sys.argv[1]
def arr(var, path):
    data = open(path, 'rb').read()
    lines = []
    for i in range(0, len(data), 19):
        lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 19]) + ',')
    return 'inline constexpr std::uint8_t %s[] = {\n%s\n};\n' % (var, '\n'.join(lines))
out = '#pragma once\n// Generated by shaders/regenerate_spirv.sh from shaders/%s.*.glsl. Do not edit.\n#include <cstdint>\n// clang-format off\nnamespace vne::xr::samples::%s_spirv {\n' % (name, name)
out += arr('kVertSpv', sys.argv[2]) + arr('kFragSpv', sys.argv[3]) + '}  // namespace vne::xr::samples::%s_spirv\n' % name
open(sys.argv[4], 'w').write(out)
PY
    echo "wrote $here/../${name}_spirv.h"
}

generate flat_color
generate text_sdf
